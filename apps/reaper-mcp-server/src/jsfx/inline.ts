/**
 * Turns a generated plugin's source into the one self-contained .jsfx file REAPER loads: the
 * `mcp_ui.jsfx-inc` toolkit is pasted into the plugin's @init, the slider metadata the toolkit
 * needs is emitted from the slider lines, and the @serialize that keeps the Advanced section's state
 * is added when missing.
 *
 * Idempotent: a file this module produced can be fed back in (an edit) and comes out with the
 * current toolkit and one copy of everything.
 */

import { readAccentToken, resolveAccent, type Accent } from './accent.js';

export const TOOLKIT_FILE = 'mcp_ui.jsfx-inc';
/**
 * Appended to every generated plugin's `desc:` (REAPER's own "Name (Developer)" convention for JS, as in
 * "JS: Spectral Hold (Cockos)"), so the maker shows in the FX list and typing "reaper-mcp" in the FX browser's
 * filter lists them all. Never changes the slug, file name, fxName, preset file or history path. "" turns it off.
 */
export const DEVELOPER_SUFFIX = ' (reaper-mcp)';
export const MAX_USER_SLIDERS = 32;
const BLOCK_START = '// ---- mcp_ui ';
const BLOCK_END = '// ---- end mcp_ui ----';
/** Lines this module adds or replaces itself: the import marker and our tags line. */
const OWN_LINE = /^\s*(import\s+mcp_ui\.jsfx-inc|tags:reaper-mcp-generated)\s*$/;
const GENERATED_COMMENT = /^\/\/ (generated by reaper-mcp|version:|toolkit:|request:|accent:)/;

export interface SliderSpec {
  index: number;
  name: string;
  min: number;
  max: number;
  step: number;
  default: number;
  /** `{A,B,C}` names, in order; empty for a plain slider */
  options: string[];
  /** A label starting with "-" hides the slider in REAPER's plain view */
  hidden: boolean;
  /** `slider3:myvar=...`: the toolkit cannot read these (see the toolkit header) */
  named: boolean;
}

const SLIDER_LINE = /^slider(\d+):(?:([A-Za-z_]\w*)=)?\s*(-?[\d.]+)\s*<\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*(?:,\s*(-?[\d.]+))?\s*(?:\{([^}]*)\})?\s*>\s*(.*)$/;

/** Every `sliderN:` line of the header. A line that starts like one but does not parse is in `bad`. */
export function parseSliders(source: string): { sliders: SliderSpec[]; bad: { line: number; text: string }[] } {
  const sliders: SliderSpec[] = [];
  const bad: { line: number; text: string }[] = [];
  const lines = source.split('\n');
  for (let i = 0; i < lines.length; i++) {
    if (/^@/.test(lines[i])) break; // sliders live in the header
    if (!/^slider\d+:/.test(lines[i])) continue;
    const m = lines[i].replace(/\r$/, '').match(SLIDER_LINE);
    if (!m) {
      bad.push({ line: i + 1, text: lines[i].trim() });
      continue;
    }
    const label = m[8].trim();
    sliders.push({
      index: Number(m[1]),
      name: label.replace(/^-/, ''),
      min: Number(m[4]),
      max: Number(m[5]),
      step: m[6] === undefined ? 0 : Number(m[6]),
      default: Number(m[3]),
      options: m[7] === undefined ? [] : m[7].split(',').map((s) => s.trim()),
      hidden: label.startsWith('-'),
      named: m[2] !== undefined,
    });
  }
  return { sliders, bad };
}

/** A number as plain decimals: EEL2 rejects "1e-7" style literals. */
function num(n: number): string {
  return String(Number(n.toFixed(6)));
}

export function toolkitVersion(toolkit: string): string {
  return toolkit.match(/toolkit, v(\d+\.\d+\.\d+)/)?.[1] ?? toolkit.match(/\bv(\d+\.\d+\.\d+)/)?.[1] ?? '0.0.0';
}

/** Drops a previous inline: the toolkit block between its markers and the lines write_jsfx adds. */
export function stripGenerated(source: string): string {
  const out: string[] = [];
  let skipping = false;
  for (const line of source.replace(/\r\n/g, '\n').split('\n')) {
    if (line.startsWith(BLOCK_START)) skipping = true;
    if (!skipping && !GENERATED_COMMENT.test(line) && !OWN_LINE.test(line)) out.push(line);
    if (skipping && line.trim() === BLOCK_END) skipping = false;
  }
  return out.join('\n');
}

export interface InlineOptions {
  toolkit: string;
  /** The plugin's own version, written in the header */
  version: number;
  /** One line from the user's request, written in the header (a comment: never sent anywhere, never shown) */
  request?: string;
  /**
   * The accent token to keep (a name or #rrggbb); undefined = the one the source already keeps, else auto.
   * 'auto' drops a kept one. Always resolved: the file gets ui_theme() with a colour.
   */
  accent?: string;
  /** The slug the auto accent is derived from (default: from the desc) */
  slug?: string;
  /** Shown in the About dialog: the day the file was written (YYYY-MM-DD) */
  date?: string;
  /** Shown in the About dialog as "(example)" */
  example?: boolean;
}

/** The desc text without our developer suffix (also used as the About dialog's plugin name). */
export function plainDesc(desc: string): string {
  let d = desc.trim();
  const suffix = DEVELOPER_SUFFIX.trim();
  while (suffix && d.toLowerCase().endsWith(suffix.toLowerCase())) d = d.slice(0, -suffix.length).trimEnd();
  return d;
}

/** `desc:` with our suffix once, after anything the plugin's own name ends with ("Width (stereo) (reaper-mcp)"). */
export function withDeveloper(desc: string): string {
  const d = plainDesc(desc);
  return DEVELOPER_SUFFIX ? `${d}${DEVELOPER_SUFFIX}` : d;
}

const eelString = (s: string) => s.replace(/["\\\r\n]/g, '').slice(0, 60);

/** The finished file. `source` may be plain source or an earlier output of this function. */
export function inlineToolkit(source: string, options: InlineOptions): string {
  const kept = readAccentToken(source);
  const lines = stripGenerated(source).split('\n');
  const first = lines.findIndex((l) => /^@/.test(l));
  const headerEnd = first === -1 ? lines.length : first;
  const header = lines.slice(0, headerEnd);
  let body = lines.slice(headerEnd);

  // header: desc first, then the lines we add, then the plugin's own header lines
  const descAt = header.findIndex((l) => /^desc:/.test(l));
  const name = descAt === -1 ? 'Plugin' : plainDesc(header[descAt].replace(/^desc:/, ''));
  if (descAt !== -1) header[descAt] = `desc:${withDeveloper(header[descAt].replace(/^desc:/, ''))}`;
  const accent = inlineAccent(options, kept, name);
  const added = [
    ...(header.some((l) => /^tags:/.test(l)) ? [] : ['tags:reaper-mcp-generated']),
    '// generated by reaper-mcp /make-plugin: edit the plugin part, never the inlined toolkit block',
    `// version: ${options.version}`,
    `// toolkit: mcp_ui ${toolkitVersion(options.toolkit)}`,
    ...(accent.token ? [`// accent: ${accent.token}`] : []),
    ...(options.request ? [`// request: ${options.request.replace(/[\r\n]+/g, ' ').slice(0, 200)}`] : []),
  ];
  header.splice(descAt + 1, 0, ...added);

  // the toolkit and the metadata it reads, right after @init
  const sliders = parseSliders(header.join('\n')).sliders;
  const about = [
    `strcpy(#ui_name, "${eelString(name)}"); strcpy(#ui_date, "${eelString(options.date ?? '')}"); strcpy(#ui_tkv, "${toolkitVersion(options.toolkit)}");`,
    `ui_pver = ${Math.max(0, Math.floor(options.version))}; ui_nctl = ${sliders.length}; ui_akind = ${accent.kind === 'custom' ? 2 : accent.kind === 'named' ? 1 : 0}; ui_example = ${options.example ? 1 : 0};`,
    `ui_theme($x${accent.hex.slice(1)});`,
  ];
  const meta = sliders.filter((s) => !s.named).flatMap((s) => [
    `ui_meta(${s.index}, ${num(s.min)}, ${num(s.max)}, ${num(s.default)}, ${num(s.step)});`,
    ...s.options.slice(0, 8).map((o, k) => `strcpy(${s.index * 8 + k}, "${o.replace(/"/g, "'")}");`),
  ]);
  const block = [
    `${BLOCK_START}${toolkitVersion(options.toolkit)} (inlined by reaper-mcp, do not edit) ----`,
    options.toolkit.replace(/\r\n/g, '\n').trimEnd(),
    ...meta,
    ...about,
    BLOCK_END,
  ];
  const initAt = body.findIndex((l) => /^@init\b/.test(l));
  if (initAt === -1) body = ['@init', ...block, '', ...body];
  else body.splice(initAt + 1, 0, ...block);

  // @serialize keeps the Advanced section open or closed with the project and presets
  if (!body.some((l) => /^@serialize\b/.test(l))) body.push('', '@serialize', 'file_var(0, ui_adv_open);');

  return [...header, ...body].join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n*$/, '\n');
}

function inlineAccent(options: InlineOptions, kept: string | undefined, name: string): Accent {
  const slug = options.slug ?? name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40).replace(/-+$/, '');
  const token = options.accent === undefined ? kept : options.accent.trim().toLowerCase() === 'auto' ? undefined : options.accent;
  return resolveAccent(slug, token);
}

/** The accent a generated file is drawn with (from its `// accent:` line, else its slug). */
export function accentOf(generated: string, slug: string): Accent {
  return resolveAccent(slug, readAccentToken(generated));
}

/** The plugin's own version from its header (`// version: 3`), or 0. */
export function readVersion(generated: string): number {
  return Number(generated.match(/^\/\/ version: (\d+)/m)?.[1] ?? 0);
}
